import 'package:firebase_auth/firebase_auth.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:flutter/material.dart';
import 'firebase_options.dart'; // generated by `, configure`
import 'screens/auth/login_screen.dart';
import 'screens/main_navigation_screen.dart';
import 'utils/theme.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  if (const bool.fromEnvironment('USE_FIREBASE_EMULATORS',
      defaultValue: false)) {
    const emulatorHost = String.fromEnvironment(
      'FIREBASE_EMULATOR_HOST',
      defaultValue: '10.0.2.2',
    );
    FirebaseAuth.instance.useAuthEmulator(emulatorHost, 9099);
    FirebaseFirestore.instance.useFirestoreEmulator(emulatorHost, 8080);
  }
  runApp(const LearnSignPHApp());
}

class LearnSignPHApp extends StatelessWidget {
  const LearnSignPHApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'LearnSign PH',
      debugShowCheckedModeBanner: false,
      theme: AppTheme.lightTheme,
      home: const AuthGate(),
    );
  }
}

/// Routes to LessonListScreen if already logged in, otherwise LoginScreen.
/// Increment 1 keeps this simple; a dedicated splash/onboarding flow can
/// be layered on top later without touching this logic.
class AuthGate extends StatelessWidget {
  final Stream<User?>? authStateStream;
  final WidgetBuilder authenticatedBuilder;
  final WidgetBuilder unauthenticatedBuilder;

  const AuthGate({
    super.key,
    this.authStateStream,
    this.authenticatedBuilder = _defaultAuthenticatedBuilder,
    this.unauthenticatedBuilder = _defaultUnauthenticatedBuilder,
  });

  static Widget _defaultAuthenticatedBuilder(BuildContext context) =>
      const MainNavigationScreen();

  static Widget _defaultUnauthenticatedBuilder(BuildContext context) =>
      const LoginScreen();

  @override
  Widget build(BuildContext context) {
    return StreamBuilder<User?>(
      stream: authStateStream ?? FirebaseAuth.instance.authStateChanges(),
      builder: (context, snapshot) {
        if (snapshot.connectionState == ConnectionState.waiting) {
          return const Scaffold(
            body: Center(
              child: Column(
                mainAxisSize: MainAxisSize.min,
                children: [
                  Image(
                    image: AssetImage(
                      'assets/images/filipino_sign_language_learning_icon.png',
                    ),
                    width: 128,
                    height: 128,
                  ),
                  SizedBox(height: 20),
                  CircularProgressIndicator(color: AppColors.primary),
                ],
              ),
            ),
          );
        }
        if (snapshot.hasData) {
          return authenticatedBuilder(context);
        }
        return unauthenticatedBuilder(context);
      },
    );
  }
}
